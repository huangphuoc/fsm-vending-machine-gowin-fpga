`timescale 1ns / 1ps

module tb_vending_machine;

    reg clk;
    reg reset_n;
    reg coin_10k_n;
    reg coin_20k_n;
    reg coin_50k_n;
    reg btn_A_n;
    reg btn_B_n;
    reg btn_C_n;
    wire buzzer;
    wire ds;
    wire stcp;
    wire shcp;
    wire led_product_A;
    wire led_product_B;
    wire led_product_C;

    top_vending_machine uut (
        .clk(clk),
        .reset_n(reset_n),
        .coin_10k_n(coin_10k_n),
        .coin_20k_n(coin_20k_n),
        .coin_50k_n(coin_50k_n),
        .btn_A_n(btn_A_n),
        .btn_B_n(btn_B_n),
        .btn_C_n(btn_C_n),
        .buzzer(buzzer),
        .ds(ds),
        .stcp(stcp),
        .shcp(shcp),
        .led_product_A(led_product_A),
        .led_product_B(led_product_B),
        .led_product_C(led_product_C)
    );

    initial begin
        $dumpfile("tb_vending_machine.vcd");
        $dumpvars(0, tb_vending_machine);

        // INIT
        clk = 0;
        reset_n = 1'b0;
        coin_10k_n = 1'b1;
        coin_20k_n = 1'b1;
        coin_50k_n = 1'b1;
        btn_A_n = 1'b0;
        btn_B_n = 1'b0;
        btn_C_n = 1'b0;

        // =========================================================
        // TEST 1: RESET
        // =========================================================
        #1000;
        reset_n = 1'b1;
        #500;
        reset_n = 1'b0;
        #500;

        // =========================================================
        // TEST 2: COIN 10K
        // =========================================================
        coin_10k_n = 1'b0;
        #1000;
        coin_10k_n = 1'b1;
        #500;

        // =========================================================
        // TEST 3: COIN 20K
        // =========================================================
        coin_20k_n = 1'b0;
        #1000;
        coin_20k_n = 1'b1;
        #500;

        // =========================================================
        // TEST 4: COIN 50K
        // =========================================================
        coin_50k_n = 1'b0;
        #1000;
        coin_50k_n = 1'b1;
        #500;

        // =========================================================
        // TEST 5: SELECT A (10K) → LED_A sáng
        // =========================================================
        btn_A_n = 1'b1;
        #1000;
        btn_A_n = 1'b0;
        #500;

        // =========================================================
        // TEST 6: NẠP THÊM 20K
        // =========================================================
        coin_20k_n = 1'b0;
        #1000;
        coin_20k_n = 1'b1;
        #500;

        // =========================================================
        // TEST 7: SELECT B (20K) → LED_B sáng
        // =========================================================
        btn_B_n = 1'b1;
        #5000;   // Giữ lâu hơn
        btn_B_n = 1'b0;
        #500;

        // =========================================================
        // TEST 8: NẠP THÊM 30K (10K + 20K)
        // =========================================================
        coin_10k_n = 1'b0;
        #1000;
        coin_10k_n = 1'b1;
        #500;
        coin_20k_n = 1'b0;
        #1000;
        coin_20k_n = 1'b1;
        #500;

        // =========================================================
        // TEST 9: SELECT C (30K) → LED_C sáng
        // =========================================================
        btn_C_n = 1'b1;
        #1000;
        btn_C_n = 1'b0;
        #500;

        // =========================================================
        // TEST 10: KHÔNG ĐỦ TIỀN MUA A (10K)
        // =========================================================
        btn_A_n = 1'b1;
        #1000;
        btn_A_n = 1'b0;
        #500;

        // =========================================================
        // TEST 11: NẠP 50K + MUA C (30K)
        // =========================================================
        coin_50k_n = 1'b0;
        #1000;
        coin_50k_n = 1'b1;
        #500;
        btn_C_n = 1'b1;
        #1000;
        btn_C_n = 1'b0;
        #500;

        // =========================================================
        // TEST 12: RESET
        // =========================================================
        #1000;
        reset_n = 1'b1;
        #500;
        reset_n = 1'b0;
        #500;

        #10000;
        $finish;
    end

    always #10 clk = ~clk;

endmodule
